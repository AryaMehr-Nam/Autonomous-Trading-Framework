class Timeframe(str, Enum):
    M1 = "1m"
    M5 = "5m"
    M15 = "15m"
    M30 = "30m"
    H1 = "1h"
    H4 = "4h"
    D1 = "1d"
    W1 = "1w"
    MN1 = "1M"

    @classmethod
    def from_string(cls, s: str) -> "Timeframe":
        """Parse various timeframe string formats."""
        mapping = {
            "M1": cls.M1, "1m": cls.M1, "1min": cls.M1,
            "M5": cls.M5, "5m": cls.M5, "5min": cls.M5,
            "M15": cls.M15, "15m": cls.M15, "15min": cls.M15,
            "M30": cls.M30, "30m": cls.M30, "30min": cls.M30,
            "H1": cls.H1, "1h": cls.H1, "60m": cls.H1,
            "H4": cls.H4, "4h": cls.H4, "240m": cls.H4,
            "D1": cls.D1, "1d": cls.D1, "daily": cls.D1,
            "W1": cls.W1, "1w": cls.W1, "weekly": cls.W1,
            "MN1": cls.MN1, "1M": cls.MN1, "monthly": cls.MN1,
        }
        result = mapping.get(s)
        if result is None:
            raise ValueError(f"Unknown timeframe: '{s}'. Valid: {list(mapping.keys())}")
        return result


