@dataclass
class EconomicEvent:
    """An economic calendar event."""
    id: str = field(default_factory=lambda: str(uuid4())[:8])
    timestamp: datetime = field(default_factory=datetime.utcnow)
    country: str = ""
    currency: str = ""
    event_name: str = ""
    impact: EventImpact = EventImpact.LOW
    actual: Optional[float] = None
    forecast: Optional[float] = None
    previous: Optional[float] = None

    @property
    def surprise(self) -> Optional[float]:
        """How much the actual deviated from forecast."""
        if self.actual is not None and self.forecast is not None and self.forecast != 0:
            return (self.actual - self.forecast) / abs(self.forecast)
        return None

    @property
    def is_high_impact(self) -> bool:
        return self.impact == EventImpact.HIGH


