@dataclass
class Tick:
    """A single price tick."""
    symbol: str
    asset_class: AssetClass
    timestamp: datetime
    bid: float
    ask: float

    @property
    def mid(self) -> float:
        return (self.bid + self.ask) / 2

    @property
    def spread(self) -> float:
        return self.ask - self.bid


@dataclass
class Candle:
    """OHLCV candle for any asset class."""
    symbol: str
    asset_class: AssetClass
    timeframe: Timeframe
    timestamp: datetime
    open: float
    high: float
    low: float
    close: float
    volume: float

    @property
    def body_size(self) -> float:
        return abs(self.close - self.open)

    @property
    def is_bullish(self) -> bool:
        return self.close > self.open

    @property
    def is_bearish(self) -> bool:
        return self.close < self.open

    @property
    def upper_wick(self) -> float:
        return self.high - max(self.open, self.close)

    @property
    def lower_wick(self) -> float:
        return min(self.open, self.close) - self.low


@dataclass
class Signal:
    """A trade signal generated by the analysis engine."""
    id: str = field(default_factory=lambda: str(uuid4())[:8])
    symbol: str = ""
    asset_class: AssetClass = AssetClass.FOREX
    signal_type: SignalType = SignalType.HOLD
    confidence: float = 0.0           # 0.0 to 1.0
    timeframe: Timeframe = Timeframe.H1
    timestamp: datetime = field(default_factory=datetime.utcnow)

    # Order type and pricing
    order_type: OrderType = OrderType.MARKET
    limit_price: float = 0.0
    
    # Price levels
    entry_price: float = 0.0
    stop_loss: float = 0.0
    take_profit: float = 0.0
    take_profit_2: Optional[float] = None  # Second TP for partial close

    # Analysis components
    technical_score: float = 0.0      # -1.0 to 1.0
    fundamental_score: float = 0.0    # -1.0 to 1.0
    sentiment_score: float = 0.0      # -1.0 to 1.0
    ml_score: float = 0.0            # -1.0 to 1.0

    # Metadata
    source: str = ""                  # Which strategy generated this
    reasoning: str = ""               # Human-readable explanation
    indicators: Dict[str, Any] = field(default_factory=dict)
    
    # Kelly Criterion Metrics
    win_rate: float = 0.50            # 0.0 to 1.0 (from backtest)
    risk_reward: float = 1.0          # Average R/R (from backtest)

    @property
    def risk_reward_ratio(self) -> float:
        if self.stop_loss == 0 or self.entry_price == 0 or self.take_profit == 0:
            return 0.0
        risk = abs(self.entry_price - self.stop_loss)
        reward = abs(self.take_profit - self.entry_price)
        return reward / risk if risk > 0 else 0.0


