@dataclass
class Position:
    """An active trading position."""
    id: str = field(default_factory=lambda: str(uuid4())[:8])
    order_id: str = ""
    signal_id: str = ""
    symbol: str = ""
    asset_class: AssetClass = AssetClass.FOREX
    side: OrderSide = OrderSide.BUY
    quantity: float = 0.0
    entry_price: float = 0.0
    current_price: float = 0.0
    stop_loss: float = 0.0
    take_profit: float = 0.0
    status: PositionStatus = PositionStatus.OPEN
    open_time: datetime = field(default_factory=datetime.utcnow)
    close_time: Optional[datetime] = None
    close_price: Optional[float] = None
    commission: float = 0.0
    swap: float = 0.0                # Overnight swap charges
    metadata: Dict[str, Any] = field(default_factory=dict)

    @property
    def unrealized_pnl(self) -> float:
        """Calculate unrealized P&L."""
        if self.side == OrderSide.BUY:
            return (self.current_price - self.entry_price) * self.quantity
        else:
            return (self.entry_price - self.current_price) * self.quantity

    @property
    def realized_pnl(self) -> float:
        """Calculate realized P&L (only when closed)."""
        if self.status != PositionStatus.CLOSED or self.close_price is None:
            return 0.0
        if self.side == OrderSide.BUY:
            gross = (self.close_price - self.entry_price) * self.quantity
        else:
            gross = (self.entry_price - self.close_price) * self.quantity
        return gross - self.commission - abs(self.swap)

    @property
    def duration_seconds(self) -> float:
        end = self.close_time or datetime.utcnow()
        return (end - self.open_time).total_seconds()

    @property
    def is_profitable(self) -> bool:
        return self.unrealized_pnl > 0


