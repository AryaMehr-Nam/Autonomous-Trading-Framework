"""
Strategy Optimizer & Institutional Quality Gate Evaluator.
==========================================================
Executes quantitative walk-forward optimization, stress-tests across market regimes,
and applies strict institutional quality gates before declaring any model 'VETTED'.
"""

import sys
if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

import copy
from typing import Dict, List, Any, Optional, Tuple
from datetime import datetime, timezone

from agents.hypothesis_engine import HypothesisEngine, TradingHypothesis
from backtesting.historical_regime_engine import HistoricalRegimeEngine
from signals.strategies.strategy_registry import strategy_registry, BaseStrategy


class StrategyOptimizerEvaluator:
    # Strict Quality Gate Thresholds
    QUALITY_GATES = {
        "min_win_rate_pct": 50.0,       # Minimum acceptable WR (with high PF)
        "target_win_rate_pct": 58.0,    # Target WR for scalpers
        "min_profit_factor": 1.45,      # Institutional minimum PF
        "min_expected_value_usd": 0.50, # Positive dollar edge per trade
        "max_drawdown_pct": 15.0,       # Strict drawdown ceiling
        "min_total_trades": 20,         # Statistical significance threshold
        "min_sharpe_ratio": 1.10,       # Risk-adjusted return threshold
    }

    def __init__(self, backtest_engine: Optional[HistoricalRegimeEngine] = None):
        self.backtest_engine = backtest_engine or HistoricalRegimeEngine()
        self.hypothesis_engine = HypothesisEngine()

    def evaluate_hypothesis(self, hypothesis: TradingHypothesis) -> Tuple[bool, Dict[str, Any]]:
        """
        Runs backtest on a single hypothesis and evaluates against quality gates.
        Returns: (passes_gates, metrics)
        """
        strat = strategy_registry.get(hypothesis.strategy_name)
        if not strat:
            return False, {"error": f"Unknown strategy {hypothesis.strategy_name}"}

        metrics = self.backtest_engine.run_strategy_backtest(strat, params=hypothesis.parameters)
        hypothesis.evaluation_metrics = metrics

        passes_gates = self.check_quality_gates(metrics)
        hypothesis.status = "VETTED" if passes_gates else ("PROMISING" if metrics["profit_factor"] >= 1.30 else "REJECTED")

        return passes_gates, metrics

    def check_quality_gates(self, metrics: Dict[str, Any]) -> bool:
        """
        Validates whether strategy metrics clear all institutional gates.
        """
        qg = self.QUALITY_GATES
        wr = metrics.get("win_rate_pct", 0.0)
        pf = metrics.get("profit_factor", 0.0)
        ev = metrics.get("expected_value_usd", 0.0)
        dd = metrics.get("max_drawdown_pct", 100.0)
        trades = metrics.get("total_trades", 0)
        sharpe = metrics.get("sharpe_ratio", 0.0)

        if trades < qg["min_total_trades"]:
            return False
        if dd > qg["max_drawdown_pct"]:
            return False
        if ev <= 0.0:
            return False
        if pf < qg["min_profit_factor"]:
            return False
        if wr < qg["min_win_rate_pct"]:
            return False
        if sharpe < qg["min_sharpe_ratio"]:
            return False

        # Multi-year consistency check: at least 2 years must be profitable
        year_bd = metrics.get("year_breakdown", {})
        if year_bd:
            profitable_years = sum(1 for yr_data in year_bd.values() if yr_data.get("net_profit", 0) > 0)
            if profitable_years < min(2, len(year_bd)):
                return False

        return True

    def calculate_fitness(self, metrics: Dict[str, Any]) -> float:
        """
        Multi-objective fitness score:
        Balances Sharpe, Profit Factor, Win Rate, and Drawdown penalty.
        """
        pf = min(metrics.get("profit_factor", 0.0), 5.0)
        sharpe = min(metrics.get("sharpe_ratio", 0.0), 5.0)
        wr = metrics.get("win_rate_pct", 0.0) / 100.0
        dd = metrics.get("max_drawdown_pct", 0.0) / 100.0
        ev = max(0.0, min(metrics.get("expected_value_usd", 0.0), 25.0)) / 10.0

        fitness = (sharpe * 0.30) + (pf * 0.30) + (wr * 0.20) + (ev * 0.20) - (dd * 0.25)
        return round(float(fitness), 3)

    def optimize_strategy(
        self,
        strategy_name: str,
        trials: int = 15,
    ) -> Dict[str, Any]:
        """
        Optimizes a strategy across candidate hypotheses generated by the engine.
        Returns detailed optimization report with champion model.
        """
        print(f"\n🔬 [OPTIMIZER] Starting optimization for strategy '{strategy_name}' ({trials} trials)...", flush=True)

        hypotheses = self.hypothesis_engine.generate_candidate_hypotheses(
            count_per_strategy=trials,
            target_strategy=strategy_name,
        )

        results = []
        champion = None
        best_fitness = -999.0

        for idx, hypo in enumerate(hypotheses, 1):
            passed, metrics = self.evaluate_hypothesis(hypo)
            fitness = self.calculate_fitness(metrics)
            metrics["fitness"] = fitness
            metrics["passed_quality_gates"] = passed
            metrics["hypothesis_id"] = hypo.hypothesis_id

            results.append({
                "hypothesis": hypo.to_dict(),
                "metrics": metrics,
                "fitness": fitness,
                "vetted": passed,
            })

            print(
                f"  Trial {idx:2d}/{trials:2d} [{hypo.hypothesis_id}] | "
                f"WR: {metrics['win_rate_pct']:>5.1f}% | PF: {metrics['profit_factor']:>4.2f} | "
                f"EV: ${metrics['expected_value_usd']:>5.2f} | DD: {metrics['max_drawdown_pct']:>4.1f}% | "
                f"Trades: {metrics['total_trades']:3d} | Fit: {fitness:>4.2f} | "
                f"{'🏆 VETTED' if passed else '❌ Rejected'}",
                flush=True
            )

            if fitness > best_fitness:
                best_fitness = fitness
                champion = {
                    "strategy_name": strategy_name,
                    "hypothesis_id": hypo.hypothesis_id,
                    "title": hypo.title,
                    "parameters": hypo.parameters,
                    "metrics": metrics,
                    "fitness": fitness,
                    "is_vetted": passed,
                }

        vetted_candidates = [r for r in results if r["vetted"]]

        print(f"\n📊 [OPTIMIZATION COMPLETE] {strategy_name}")
        print(f"  Total Trials Tested : {len(results)}")
        print(f"  Vetted (Passed Gates): {len(vetted_candidates)}")
        if champion:
            print(f"  Champion Model      : {champion['hypothesis_id']} (Fitness: {champion['fitness']})")
            print(f"  Champion Vetted     : {champion['is_vetted']}")

        return {
            "strategy_name": strategy_name,
            "trials_run": len(results),
            "vetted_count": len(vetted_candidates),
            "champion": champion,
            "all_results": results,
            "timestamp": datetime.now(timezone.utc).isoformat(),
        }
